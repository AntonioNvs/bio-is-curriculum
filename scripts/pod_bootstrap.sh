#!/usr/bin/env bash
#
# pod_bootstrap.sh — prepare a RunPod pod to run the bio-is-curriculum campaigns.
#
# WHY THIS EXISTS
# The campaign YAMLs assume a host with a Docker daemon and 8 GPUs, with
# `gpu_id` pinned in the YAML and `docker run --gpus device=N` doing the GPU
# selection. A RunPod pod has none of that: no Docker daemon, one GPU, and an
# ephemeral root filesystem. This script closes the gap.
#
# It is SAFE TO RE-RUN: every step is guarded by an existence check, so a pod
# that died mid-bootstrap (or a fresh pod reattached to the same volume) just
# resumes.
#
# THE TWO TRAPS IT DEFUSES
#
# 1. No Docker daemon. `cli/experiment.py` decides `use_docker` from
#    `spec.docker is not None`, and all 24 campaign YAMLs have a `docker:` block,
#    so without `--no-docker` the runner shells out to a Docker CLI that does not
#    exist. run_campaign.py always passes `--no-docker`; BIO_IS_IN_DOCKER=1 below
#    is the independent second guard.
#
# 2. The CUDA_VISIBLE_DEVICES=7 pin. `config/cuda.py::configure_cuda_device`
#    skips pinning only when `running_in_docker()` is true or when
#    CUDA_VISIBLE_DEVICES is already exported; otherwise it pins the default
#    physical GPU 7 (DEFAULTS["cuda_device_id"]). On a 1-GPU pod that hides the
#    only GPU and the run silently falls back to CPU — which looks exactly like a
#    slow run. The trigger is live: cli/experiment.py always passes
#    `--cuda-device-id 7` to every fold subprocess. Exporting
#    CUDA_VISIBLE_DEVICES=0 short-circuits it before the argv parse, and
#    BIO_IS_IN_DOCKER=1 short-circuits it earlier still. Step 9 proves this
#    behaviourally rather than trusting the variables are set.
#
# USAGE
#   bash scripts/pod_bootstrap.sh
#   REPO_REF=<branch|tag|sha> bash scripts/pod_bootstrap.sh   # pin a revision
#
# Everything written outside /workspace is lost when the pod is replaced: the uv
# binary (~/.local/bin), the HF cache default, the uv cache, /tmp, and anything
# installed by apt. Keeping the repo (with .venv and datasets/) on the volume
# means a clean pod only needs this script re-run.

set -euo pipefail

WORKSPACE="${WORKSPACE:-/workspace}"
REPO_DIR="$WORKSPACE/bio-is-curriculum"
REPO_URL="${REPO_URL:-https://github.com/AntonioNvs/bio-is-curriculum.git}"
REPO_REF="${REPO_REF:-main}"
HF_CACHE="$WORKSPACE/hf-cache"
UV_CACHE="$WORKSPACE/uv-cache"
LOG_DIR="$WORKSPACE/logs"
STATE_DIR="$WORKSPACE/state"
ENV_FILE="$WORKSPACE/env.sh"

# Only what the runbook's campaigns need. medline is deferred in Y1 (see the
# header of factorial_matched_2x2.yaml), so it is not fetched by default.
DATASETS="${DATASETS:-reuters90 books dblp agnews yelp_2013}"

NCPU="$(nproc)"
THREADS=$(( NCPU < 16 ? NCPU : 16 ))

step() { printf '\n=== [%s] %s ===\n' "$1" "$2"; }
ok()   { printf '  ok: %s\n' "$1"; }

step 1 "Workspace layout"
mkdir -p "$HF_CACHE" "$UV_CACHE" "$LOG_DIR" "$STATE_DIR"
ok "$WORKSPACE/{hf-cache,uv-cache,logs,state}"

# ---------------------------------------------------------------------------
step 2 "Environment block -> $ENV_FILE"
# PYTHONHASHSEED must come from the parent environment. cli/main.py does
# os.environ.setdefault("PYTHONHASHSEED", "42") at import time, but the hash seed
# is fixed at interpreter startup, so that line is a no-op for the current
# process. CUBLAS_WORKSPACE_CONFIG via setdefault does work (it runs before torch
# is imported), but exporting both here is the reliable form.
cat > "$ENV_FILE" <<EOF
# Generated by scripts/pod_bootstrap.sh — do not edit by hand.
# Source this from any shell that launches a campaign.

# Defuses the CUDA_VISIBLE_DEVICES=7 pin (config/cuda.py:37-41) and makes
# use_docker false independently of --no-docker.
export BIO_IS_IN_DOCKER=1
export CUDA_VISIBLE_DEVICES=0

# Determinism. Must be exported before the interpreter starts (see step 2 note).
export PYTHONHASHSEED=42
export CUBLAS_WORKSPACE_CONFIG=:4096:8

# Match the paper's 16-core budget, capped at what the pod actually has.
export OMP_NUM_THREADS=$THREADS
export MKL_NUM_THREADS=$THREADS

# Keep caches on the volume so a replaced pod does not re-download.
export HF_HOME=$HF_CACHE
export UV_CACHE_DIR=$UV_CACHE

export TOKENIZERS_PARALLELISM=false
export PYTHONUNBUFFERED=1
EOF
ok "wrote $ENV_FILE (OMP/MKL threads: $THREADS of $NCPU cores)"

# shellcheck source=/dev/null
source "$ENV_FILE"
ok "sourced into this shell"

BASHRC="$HOME/.bashrc"
BEGIN_MARK="# >>> bio-is-curriculum env >>>"
END_MARK="# <<< bio-is-curriculum env <<<"
if ! grep -qF "$BEGIN_MARK" "$BASHRC" 2>/dev/null; then
  {
    printf '\n%s\n' "$BEGIN_MARK"
    printf '[ -f "%s" ] && source "%s"\n' "$ENV_FILE" "$ENV_FILE"
    printf '%s\n' "$END_MARK"
  } >> "$BASHRC"
  ok "injected into $BASHRC"
else
  ok "already present in $BASHRC"
fi

# ---------------------------------------------------------------------------
step 3 "uv"
if ! command -v uv >/dev/null 2>&1; then
  # ~/.local/bin is not on the volume, so this repeats on a fresh pod.
  curl -LsSf https://astral.sh/uv/install.sh | sh
fi
export PATH="$HOME/.local/bin:$PATH"
command -v uv >/dev/null 2>&1 || { echo "FAIL: uv not on PATH after install" >&2; exit 1; }
ok "uv $(uv --version)"

# ---------------------------------------------------------------------------
step 4 "Repository -> $REPO_DIR"
if [ ! -d "$REPO_DIR/.git" ]; then
  git clone "$REPO_URL" "$REPO_DIR"
  ok "cloned"
else
  ok "already cloned"
fi
git -C "$REPO_DIR" fetch --prune origin
git -C "$REPO_DIR" checkout --quiet "$REPO_REF"
# If the ref names a branch, fast-forward it to the remote. A tag or SHA is left
# detached, which is what pinning a revision means.
if git -C "$REPO_DIR" rev-parse --verify --quiet "origin/$REPO_REF" >/dev/null; then
  git -C "$REPO_DIR" merge --ff-only --quiet "origin/$REPO_REF"
fi
ok "ref=$REPO_REF commit=$(git -C "$REPO_DIR" rev-parse --short HEAD)"

# ---------------------------------------------------------------------------
step 5 "C toolchain"
# ModernBERT/Triton JIT-compiles kernels and needs a C compiler. The Dockerfile
# installs build-essential; a bare pod image may not have it.
if command -v gcc >/dev/null 2>&1; then
  ok "gcc $(gcc -dumpversion)"
else
  if command -v apt-get >/dev/null 2>&1; then
    apt-get update -qq && apt-get install -y -qq --no-install-recommends build-essential
    ok "installed build-essential"
  else
    echo "WARN: no gcc and no apt-get; Triton JIT may fail." >&2
  fi
fi

# ---------------------------------------------------------------------------
step 6 "Python environment (uv sync --frozen)"
cd "$REPO_DIR"
# --frozen: install exactly uv.lock. Do not let a resolve change torch under us.
uv sync --frozen
ok "synced"

# ---------------------------------------------------------------------------
step 7 "Verify the torch/CUDA pair"
# uv sync can replace the CUDA wheel, so this check belongs AFTER it, not before.
uv run python - <<'PY'
import sys
import torch

print(f"  python {sys.version.split()[0]}")
print(f"  torch  {torch.__version__} (cuda {torch.version.cuda})")
if not torch.cuda.is_available():
    raise SystemExit("FAIL: torch.cuda.is_available() is False after uv sync")
print(f"  gpu    {torch.cuda.get_device_name(0)}")
PY

# ---------------------------------------------------------------------------
step 8 "Datasets + HF cache"
for ds in $DATASETS; do
  if [ -d "$REPO_DIR/datasets/$ds" ]; then
    ok "dataset $ds already present"
  else
    echo "  downloading $ds ..."
    uv run python download_datasets.py "$ds"
  fi
done

# Warm the HF cache into the volume so the first training run does not pay for it.
uv run python - <<'PY'
from transformers import AutoModelForSequenceClassification, AutoTokenizer

for name in ("answerdotai/ModernBERT-base", "roberta-base"):
    AutoTokenizer.from_pretrained(name)
    AutoModelForSequenceClassification.from_pretrained(name)
    print(f"  cached {name}")
PY

# ---------------------------------------------------------------------------
step 9 "Behavioural sanity — is the GPU actually visible?"
# Setting the variables is not evidence; this runs the real code paths.
uv run python - <<'PY'
import os

from bio_is_curriculum.config.cuda import configure_cuda_device, running_in_docker

if not running_in_docker():
    raise SystemExit("FAIL: running_in_docker() is False — the env block is not in effect")

# Must be called before torch is imported (config/cuda.py docstring).
applied = configure_cuda_device()
if applied is not None:
    raise SystemExit(
        f"FAIL: CUDA pinning fired and set CUDA_VISIBLE_DEVICES={applied}. "
        "On a single-GPU pod this hides the only GPU and training falls back to CPU."
    )
if os.environ.get("CUDA_VISIBLE_DEVICES") != "0":
    raise SystemExit(
        f"FAIL: CUDA_VISIBLE_DEVICES={os.environ.get('CUDA_VISIBLE_DEVICES')!r}, expected '0'"
    )

import torch

if not torch.cuda.is_available() or torch.cuda.device_count() < 1:
    raise SystemExit("FAIL: no CUDA device visible")

print(f"  pinning skipped, CUDA_VISIBLE_DEVICES=0, device={torch.cuda.get_device_name(0)}")
PY

# The end-to-end check: the real CLI, on a real campaign file, must expand the
# expected number of fold jobs. Catches a broken YAML or a missing dataset.
SMOKE_JOBS="$(uv run bio-experiment experiments/campaigns/factorial_matched_2x2.yaml \
  --no-docker --dataset reuters90 --folds 0 --dry-run \
  | grep -cE '^\[[0-9]+/[0-9]+\]' || true)"
if [ "$SMOKE_JOBS" -ne 4 ]; then
  echo "FAIL: Y1 dry-run emitted $SMOKE_JOBS job lines, expected 4 (raw/is/cl/is_cl)." >&2
  exit 1
fi
ok "Y1 dry-run emits 4 jobs for reuters90 fold 0"

# ---------------------------------------------------------------------------
cat <<EOF

Bootstrap complete.

  repo     $REPO_DIR @ $(git -C "$REPO_DIR" rev-parse --short HEAD)
  env      $ENV_FILE
  logs     $LOG_DIR
  state    $STATE_DIR

Next: launch the campaign.

run_campaign.py does NOT read $ENV_FILE itself, and it refuses to execute
without BIO_IS_IN_DOCKER=1 (a bare-metal run would silently pin GPU 7 on a
1-GPU pod and train on CPU). An interactive shell picks the value up from the
~/.bashrc block above, but `nohup bash -c '...'` never reads ~/.bashrc — the
run then dies at preflight with "FAIL: BIO_IS_IN_DOCKER is not '1'". Source it
inside the command that runs the campaign:

  cd $REPO_DIR
  source $ENV_FILE
  uv run python scripts/run_campaign.py --dry-run            # list the shards
  nohup bash -c "source $ENV_FILE && uv run python scripts/run_campaign.py" \
      > $LOG_DIR/campaign.log 2>&1 &

  uv run python scripts/run_campaign.py --status             # progress + heartbeat
EOF
